WORKFLOW = """在一次 API 请求的一次响应中，按顺序完成“最小事件大纲 → 最终分镜 → H3”。这是组织顺序，不是多次请求；不输出推理过程，不调用工具。

第一阶段：最小事件大纲
1. 识别 generate、reference_transfer、edit 或 continuation。把用户明确要求、参考依据和开放部分分别记录在 creative_brief 与 bindings；完整分镜、严格复刻和局部编辑按锁定范围执行，未指定部分只作完成目标所需的补全。
2. 建立简短、单向的 developments。每条只写人物、物体、空间、关系、信息或产品状态发生的可见变化和结果，不写镜头、景别、运镜、转场或特效。连续的预兆、触发、动作、即时反应和直接结果按同一目标聚合；变亮、变响、变震、换角度、换景别、标题动画、白闪、黑场、故障和其他特效变化不是独立事件，附着到它们所表现或连接的内容事件。没有用户依据时不重复启动动作、不重复高潮、不在离开后返回起点，也不让完成的结果再次发生。

第二阶段：最终分镜
3. 先判断用户是否锁定镜头或剪辑结构；锁定部分原样执行。开放部分遵循四条规则：
- 完整保留用户明确要求，采用完成意图所需的最小充分补全。
- 同一时间、同一空间、同一主体和同一动作目标默认在一个连续镜头内完成。
- 只有时间或空间改变、观看对象真正改变、当前镜头通过主体运动/运镜/构图/景别渐变/焦点变化仍无法呈现必要信息，或用户/参考明确要求时才切镜。
- 剪辑风格只决定必要切点怎样表现，不决定增加事件或镜头；快速、硬切、电影感、闪白、黑场、故障、震动和普通反应不能单独授权切镜。用户要求某个效果、标题动画或短黑场，只锁定它必须出现，不等于锁定独立 Shot；除非用户明确说“单独一镜”“独立片段”或“标题卡”，否则把它嵌入相邻内容镜头。
4. 一个镜头可以连续完成多个动作阶段。产品细节在拿取、使用、转动或移动过程中显露；人物反应和触发动作尽量保持在同一段；摄影机可以在镜头内连续跟拍、推进、摇移、改变构图、景别和焦点。不要为了覆盖大全景、中景、近景和特写而机械拆镜。每个 Shot 至少承载一个内容 development；纯标题变化、纯闪白、纯黑场、纯故障、纯震动、纯反应或仅改变景别/角度不能独立成镜，用户或参考明确锁定者除外。
5. 仅当同一时空、主体和动作目标仍被拆开时，后镜才写 cut_reason，说明当前镜头为什么无法呈现必要信息，并写 continuity_bridge。普通镜头不需要解释切镜。完成分镜后只问：删除切点后动作能否自然连续？后镜是否有当前镜头无法呈现的新信息？切点是否来自用户、参考或真实时空/观看对象变化？若第一问为“能”且后两问为“否”，合并。

第三阶段：写 H3
6. content_plan 中每镜保留 start_seconds 和 end_seconds 以检查完整覆盖目标时长；最终 H3 中每个 Shot 默认只在开头写一个绝对起始时间。除非用户明确指定镜内时刻，不写第二个绝对时间，也不写微时间表。镜内阶段用“随后、同时、动作继续、镜头顺势跟随、在动作完成时、最终停在”等自然顺序表达。
7. 跨切镜续接动作阶段、运动方向、观察侧、相对位置和物品归属。需要流动感时在动作进行中切出并从未完成阶段切入，不停住或重演；将必要的 continuity_bridge 实际写入前镜结尾和后镜开头，而不是只留在 content_plan。
8. 模糊、闪白、烟雾、暗场、故障或遮挡用于替换内容时，只替换计划指定的范围：“旧内容完全不可辨识 → 遮蔽峰值完成替换 → 只显露新内容”。峰值后的第一帧可辨识内容属于新状态，被替换的旧内容不自行回闪、混合或恢复。用户明确要求跨转场保留、叠加、回闪或再次出现的内容原样执行。
9. 按随附 H3 skill 写完整六节 h3_prompt。先从最终镜头提取 sound_cues，再分别形成 overall_soundscape 与 non_diegetic_music：前者只汇总有物理或叙事依据的场景内声音，后者先判断是否需要配乐，允许 N/A；需要精确同步或跨镜延续的声音同时落实到对应 Shot，结尾板块不逐镜重复。
10. 最终只检查：用户明确要求是否全部落实；事件是否单向推进且没有重复；镜头是否为最小充分数量；每镜是否只有一个默认绝对时间锚点；动作、方向、空间、持物和隐藏式替换是否连续；每项主要声音是否有触发依据、声音分类是否正确、配乐是否确有必要并与已规划节奏一致。发现问题直接修正最终 developments、shots 和 H3，content_plan 只保存最终版。"""

